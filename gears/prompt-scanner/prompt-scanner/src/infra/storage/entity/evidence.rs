//! `SeaORM` entity for the `evidences` table: one row per finding of a
//! flagged scan. See `migrations::m20260805_000001_initial` for the DDL.
//!
//! Rows are append-only: inserted once, never updated. Deletion (expiry,
//! manual removal, tenant deletion) is the only other write.

use chrono::{DateTime, Utc};
use sea_orm::entity::prelude::*;
use toolkit_db_macros::Scopable;
use uuid::Uuid;

#[derive(Clone, Debug, PartialEq, DeriveEntityModel, Scopable)]
#[sea_orm(table_name = "evidences")]
#[secure(tenant_col = "tenant_id", resource_col = "trace_id", no_owner, no_type)]
pub struct Model {
    /// One scan; UUID v7, generated by the scanner.
    #[sea_orm(primary_key, auto_increment = false)]
    pub trace_id: Uuid,
    /// The finding's position in the scan, 0..=255.
    #[sea_orm(primary_key, auto_increment = false)]
    pub ordinal: i16,
    pub tenant_id: Uuid,
    /// The consumer's id for the request.
    pub correlation_id: Option<String>,
    pub connector_id: String,
    /// Serialized `prompt_scanner_sdk::ContentKind` (`snake_case` tag).
    pub content_kind: String,
    pub created_at: DateTime<Utc>,
    /// The row counts as deleted from this moment.
    pub expires_at: DateTime<Utc>,
    /// The scan's verdict: serialized `prompt_scanner_sdk::VerdictAction`.
    pub action: String,
    /// The policy's settings format, e.g. `1.0`.
    pub settings_schema: Option<String>,
    /// The scanner backend's GTS instance id.
    pub detector: String,
    pub detector_version: Option<String>,
    pub category: String,
    /// Serialized `prompt_scanner_sdk::Severity`.
    pub severity: String,
    pub confidence: f32,
    /// The scanner's own suggestion: serialized `VerdictAction`.
    pub suggested_action: String,
    /// Bytes in the scanned text; `None` = no location.
    pub span_start: Option<i32>,
    pub span_end: Option<i32>,
    /// `None` unless the tenant policy enables evidence.
    pub excerpt: Option<String>,
    /// Bytes: where the excerpt starts in the scanned text.
    pub excerpt_start: Option<i32>,
}

#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
pub enum Relation {}

impl ActiveModelBehavior for ActiveModel {}
